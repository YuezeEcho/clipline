import AppKit
import Combine
import CryptoKit
import ImageIO

/// Clipboard contents never leave memory. Only tracking preferences may be persisted.
@MainActor
final class ClipboardHistory: ObservableObject {
    enum Content {
        case text(String)
        case image(Data, NSImage)

        var byteCount: Int {
            switch self {
            case .text(let text): return text.utf8.count
            case .image(let data, _): return data.count
            }
        }

        var fingerprint: String {
            let data: Data
            let prefix: String
            switch self {
            case .text(let text): data = Data(text.utf8); prefix = "text:"
            case .image(let png, _): data = png; prefix = "image:"
            }
            return prefix + SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        }
    }

    struct Entry: Identifiable {
        let id: UUID
        let content: Content
        let fingerprint: String
        var copiedAt: Date
        var source: String
        let tilt: Double
    }

    @Published private(set) var entries: [Entry] = []
    @Published private(set) var copiedID: UUID?
    @Published private(set) var isTracking = true
    var onChange: (() -> Void)?
    var hitRects: [UUID: CGRect] = [:]
    var interactionRect: CGRect = .zero

    static let maximumEntries = 100
    static let maximumTextBytes = 1_048_576
    static let maximumImageBytes = 16 * 1_048_576
    static let maximumTotalBytes = 64 * 1_048_576

    private let pasteboard: NSPasteboard
    private let capacity: Int
    private let byteBudget: Int
    private var lastChangeCount: Int
    private var pendingChangeCount: Int?
    private var pendingReadAttempts = 0
    private var timer: Timer?
    // Writers can declare a copy before supplying data without incrementing
    // changeCount again. Retry at most six times (normally about three seconds).
    // Unsupported formats must not cause data reads on every poll indefinitely.
    private static let maximumReadAttempts = 6

    init(pasteboard: NSPasteboard = .general, capacity: Int? = nil,
         byteBudget: Int? = nil) {
        self.pasteboard = pasteboard
        self.capacity = max(1, capacity ?? Self.maximumEntries)
        self.byteBudget = max(1, byteBudget ?? Self.maximumTotalBytes)
        // Do not import anything already on the clipboard before launch.
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        clear()
    }

    func setTracking(_ enabled: Bool) {
        // Discard changes made while paused, including when a poll was not due yet.
        finishReading(pasteboard.changeCount)
        isTracking = enabled
    }

    func poll() {
        let change = pasteboard.changeCount
        guard change != lastChangeCount else { return }
        guard isTracking else { finishReading(change); return }
        if pendingChangeCount != change {
            pendingChangeCount = change
            pendingReadAttempts = 0
        }
        pendingReadAttempts += 1

        // Respect the conventional markers used by password managers and other apps.
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                        "org.nspasteboard.AutoGeneratedType"]
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard !excluded.contains(where: types.contains) else { finishReading(change); return }

        let content: Content?
        if let png = pasteboard.data(forType: .png), let image = Self.imageContent(png) {
            content = image
        } else if let tiff = pasteboard.data(forType: .tiff), let image = Self.imageContent(tiff) {
            content = image
        } else if let text = pasteboard.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  text.utf8.count <= Self.maximumTextBytes {
            content = .text(text)
        } else {
            content = nil
        }
        // A lazy data provider can change the pasteboard while we are reading it.
        guard pasteboard.changeCount == change else { return }
        guard let content else {
            if pendingReadAttempts >= Self.maximumReadAttempts { finishReading(change) }
            return
        }
        finishReading(change)
        record(content, source: NSWorkspace.shared.frontmostApplication?.localizedName ?? "")
    }

    private func finishReading(_ change: Int) {
        lastChangeCount = change
        pendingChangeCount = nil
        pendingReadAttempts = 0
    }

    /// Decode only bounded images; retain the original PNG and a small display thumbnail.
    static func imageContent(_ data: Data) -> Content? {
        guard data.count <= maximumImageBytes,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, Double(width) * Double(height) <= 40_000_000 else { return nil }
        let png: Data
        if CGImageSourceGetType(source) as String? == "public.png" {
            png = data
        } else {
            guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
                  let encoded = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]),
                  encoded.count <= maximumImageBytes else { return nil }
            png = encoded
        }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 480
        ]
        guard let thumb = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return .image(png, NSImage(cgImage: thumb, size: NSSize(width: thumb.width, height: thumb.height)))
    }

    func record(_ content: Content, source: String, at date: Date = Date()) {
        guard content.byteCount <= byteBudget else { return }
        let fingerprint = content.fingerprint
        var entry: Entry
        if let index = entries.firstIndex(where: { $0.fingerprint == fingerprint }) {
            entry = entries.remove(at: index)
            entry.copiedAt = date
            entry.source = source
        } else {
            entry = Entry(id: UUID(), content: content, fingerprint: fingerprint,
                          copiedAt: date, source: source, tilt: .random(in: -1.8...1.8))
        }
        entries.insert(entry, at: 0)
        var total = entries.reduce(0) { $0 + $1.content.byteCount }
        while entries.count > capacity || total > byteBudget {
            total -= entries.removeLast().content.byteCount
        }
        if let copiedID, !entries.contains(where: { $0.id == copiedID }) { self.copiedID = nil }
        onChange?()
    }

    @discardableResult
    func copy(_ id: UUID) -> Bool {
        guard let entry = entries.first(where: { $0.id == id }) else { return false }
        let item = NSPasteboardItem()
        switch entry.content {
        case .text(let text): item.setString(text, forType: .string)
        case .image(let data, _): item.setData(data, forType: .png)
        }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects([item])
        // Our own write must not create or reorder a history entry.
        finishReading(pasteboard.changeCount)
        guard success else { return false }
        copiedID = id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.copiedID == id { self?.copiedID = nil }
        }
        return true
    }

    func remove(_ id: UUID) {
        entries.removeAll { $0.id == id }
        hitRects[id] = nil
        if copiedID == id { copiedID = nil }
        onChange?()
    }

    func clear() {
        entries.removeAll()
        hitRects.removeAll()
        copiedID = nil
        finishReading(pasteboard.changeCount)
        onChange?()
    }
}
